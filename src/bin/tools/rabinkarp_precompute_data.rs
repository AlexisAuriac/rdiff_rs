use std::{
    env,
    fs::OpenOptions,
    io::{stdout, Write},
    num::Wrapping,
};

use anyhow::Error;
use rdiff::weak_sum::rabin_karp_consts::RABINKARP_MULT;

pub fn rabinkarp_precompute_data(n: u32, output: Option<String>) -> Result<(), Error> {
    let mut output: Box<dyn Write> = match output {
        None => Box::new(stdout()),
        Some(path) => {
            let f = OpenOptions::new()
                .write(true)
                .create(true)
                .truncate(true)
                .open(path)?;
            Box::new(f)
        }
    };

    let mut m = Wrapping(1);

    let cmd = env::args().collect::<Vec<String>>().join(" ");
    writeln!(output, "// generated by `{}`", cmd)?;

    writeln!(output, "[")?;
    for i in 1..=n {
        m *= RABINKARP_MULT;

        writeln!(output, "\t{:#010x}, // m^{}", m, i)?;
    }
    writeln!(output, "]")?;

    Ok(())
}
